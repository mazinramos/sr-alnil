ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "artifacts", "nile-secrets", "src")
OUT = os.path.join(ROOT, "docs", "dialect", "WORDS_USED.md")
AR = re.compile(r"[\u0600-\u06FF]")
SKIP_KEYS = r"(?:id|background|character|image|icon|speaker|source|dest|type)"
STR = re.compile(r'"((?:[^"\\\n]|\\.)*)"|\'((?:[^\'\\\n]|\\.)*)\'|`((?:[^`\\]|\\.)*)`')

def literals(text, skip_prefix=SKIP_KEYS):
    for m in STR.finditer(text):
        s = m.group(1) or m.group(2) or m.group(3) or ""
        if not AR.search(s): continue
        pre = text[max(0, m.start() - 24):m.start()]
        if re.search(skip_prefix + r"\s*:\s*$", pre): continue
        yield s

records = []   # (location, text)
for f in sorted(glob.glob(os.path.join(SRC, "content", "chapters", "ch[0-9].ts"))):
    ch = os.path.basename(f)[:-3]
    cur = ch
    for line in open(f, encoding="utf-8"):
        m = re.search(r'\bid:\s*"(c\d-l\d)"', line)
        if m: cur = m.group(1)
        for s in literals(line):
            records.append((cur, s))
for f in sorted(glob.glob(os.path.join(SRC, "**", "*.ts*"), recursive=True)):
    rel = os.path.relpath(f, SRC)
    if rel.startswith(os.path.join("content", "chapters")) or rel.endswith(("types.ts", "demo.ts")) or ".test." in rel: continue
    txt = open(f, encoding="utf-8").read()
    for s in literals(txt): records.append(("ui:" + rel, s))
    for m in re.finditer(r">([^<>{}\n]*[\u0600-\u06FF][^<>{}\n]*)<", txt): records.append(("ui:" + rel, m.group(1)))

TOK = re.compile(r"[\u0600-\u06FF\u064B-\u0652]+")
def tokens(s): return [t.replace("\u0640", "") for t in TOK.findall(s)]

